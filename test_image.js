// Create a minimal valid JPEG for testing
import fs from 'fs';

// Minimal JPEG header + red 10x10 image
const minimalJPEG = Buffer.from([
  0xFF, 0xD8, // SOI (Start of Image)
  0xFF, 0xE0, // APP0
  0x00, 0x10, // Length
  0x4A, 0x46, 0x49, 0x46, 0x00, // "JFIF\0"
  0x01, 0x01, // Version
  0x01, // Units
  0x00, 0x48, 0x00, 0x48, // X,Y density
  0x00, 0x00, // Thumbnail width, height
  
  0xFF, 0xC0, // SOF0 (Start of Frame)
  0x00, 0x11, // Length
  0x08, // Precision
  0x00, 0x0A, 0x00, 0x0A, // Height, Width (10x10)
  0x03, // Components
  0x01, 0x22, 0x00, // Y component
  0x02, 0x11, 0x01, // Cb component  
  0x03, 0x11, 0x01, // Cr component
  
  0xFF, 0xC4, // DHT (Define Huffman Table)
  0x00, 0x14, // Length
  0x00, // DC table 0
  0x01, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  
  0xFF, 0xDA, // SOS (Start of Scan)
  0x00, 0x0C, // Length
  0x03, // Components
  0x01, 0x00, // Component 1
  0x02, 0x11, // Component 2
  0x03, 0x11, // Component 3
  0x00, 0x3F, 0x00, // Spectral selection
  
  // Minimal compressed data (red 10x10)
  0xFF, 0x00, 0xFF, 0x00, 0xFF, 0x00, 0xFF, 0x00,
  
  0xFF, 0xD9 // EOI (End of Image)
]);

fs.writeFileSync('attached_assets/test_minimal.jpg', minimalJPEG);
console.log('Created minimal test JPEG:', minimalJPEG.length, 'bytes');
console.log('Base64 preview:', minimalJPEG.toString('base64').substring(0, 100));